    (6, 'RA'),
    (7, 'KM')
ON CONFLICT (position_id) DO NOTHING;

-- 3. RPC-FUNKTION FÜR DIREKTEN KMP-SYNC (/rest/v1/rpc/sync_handball_snapshot)
-- Vergleicht lastUpdatedEpochMillis, speichert den neuesten Stand in app_snapshots
-- UND spiegelt alle Entitäten sauber in die 12 relationalen PostgreSQL-Tabellen.

CREATE OR REPLACE FUNCTION public.sync_handball_snapshot(incoming_snapshot JSONB)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    existing_record public.app_snapshots%ROWTYPE;
    incoming_ts BIGINT;
    incoming_club TEXT;
BEGIN
    incoming_ts := COALESCE((incoming_snapshot->>'lastUpdatedEpochMillis')::BIGINT, 0);
    incoming_club := COALESCE(incoming_snapshot->>'ownClubName', 'HC Handball Löwen');

    SELECT * INTO existing_record
    FROM public.app_snapshots
    WHERE snapshot_key = 'default'
    FOR UPDATE;

    -- Wenn bereits ein neuerer Snapshot in Supabase liegt, gib diesen direkt zurück
    IF FOUND AND existing_record.last_updated_epoch_millis > incoming_ts THEN
        RETURN existing_record.payload;
    END IF;

    -- Andernfalls ist incoming_snapshot neuer (oder der erste Sync überhaupt):
    INSERT INTO public.app_snapshots (snapshot_key, own_club_name, last_updated_epoch_millis, payload, updated_at)
    VALUES ('default', incoming_club, incoming_ts, incoming_snapshot, NOW())
    ON CONFLICT (snapshot_key) DO UPDATE
    SET own_club_name = EXCLUDED.own_club_name,
        last_updated_epoch_millis = EXCLUDED.last_updated_epoch_millis,
        payload = EXCLUDED.payload,
        updated_at = NOW();

    -- Relationale Tabellen aus dem Snapshot aktualisieren (damit im Supabase Table Editor
    -- und für SQL-Analysen immer alle Tabellen exakt synchron sind)
    DELETE FROM public.coach_gamestats WHERE true;
    DELETE FROM public.timeout WHERE true;
    DELETE FROM public.goal_keeper_gamestats WHERE true;
    DELETE FROM public.field_player_gamestats WHERE true;
    DELETE FROM public.game_log WHERE true;
    DELETE FROM public.player_game WHERE true;
    DELETE FROM public.game WHERE true;
    DELETE FROM public.season_opponent WHERE true;
    DELETE FROM public.opponent_teams WHERE true;
    DELETE FROM public.season WHERE true;
    DELETE FROM public.player WHERE true;
    DELETE FROM public.position WHERE true;

    -- POSITION
    INSERT INTO public.position (position_id, position_name)
    SELECT
        (item->>'positionId')::INTEGER,
        COALESCE(item->>'positionName', '')
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'positions', '[]'::JSONB)) AS item;

    -- PLAYER
    INSERT INTO public.player (
        player_id, position_id, first_name, last_name, email, role,
        jersey_number_home_kit, jersey_number_away_kit
    )
    SELECT
        (item->>'playerId')::INTEGER,
        NULLIF(item->>'positionId', '')::INTEGER,
        COALESCE(item->>'firstName', ''),
        COALESCE(item->>'lastName', ''),
        COALESCE(item->>'email', ''),
        COALESCE(item->>'role', 'FIELD_PLAYER'),
        NULLIF(item->>'jerseyNumberHomeKit', '')::INTEGER,
        NULLIF(item->>'jerseyNumberAwayKit', '')::INTEGER
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'players', '[]'::JSONB)) AS item;

    -- SEASON
    INSERT INTO public.season (season_id, division, start_of_season, end_of_season)
    SELECT
        (item->>'seasonId')::INTEGER,
        COALESCE(item->>'division', ''),
        COALESCE(item->>'startOfSeason', ''),
        COALESCE(item->>'endOfSeason', '')
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'seasons', '[]'::JSONB)) AS item;

    -- OPPONENT_TEAMS
    INSERT INTO public.opponent_teams (opponent_team_id, opponent_name, opponent_location)
    SELECT
        (item->>'opponentTeamId')::INTEGER,
        COALESCE(item->>'opponentName', ''),
        COALESCE(item->>'opponentLocation', '')
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'opponentTeams', '[]'::JSONB)) AS item;

    -- SEASON_OPPONENT
    INSERT INTO public.season_opponent (season_id, opponent_team_id)
    SELECT
        (item->>'seasonId')::INTEGER,
        (item->>'opponentTeamId')::INTEGER
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'seasonOpponents', '[]'::JSONB)) AS item
    ON CONFLICT DO NOTHING;

    -- GAME
    INSERT INTO public.game (
        game_id, season_id, opponent_id, second_opponent_id, is_home_game,
        location, game_type, game_date,
        home_team_halftime_score, away_team_halftime_score,
        home_team_score, away_team_score, elapsed_seconds
    )
    SELECT
        (item->>'gameId')::INTEGER,
        (item->>'seasonId')::INTEGER,
        (item->>'opponentId')::INTEGER,
        NULLIF(item->>'secondOpponentId', '')::INTEGER,
        COALESCE((item->>'isHomeGame')::BOOLEAN, TRUE),
        COALESCE(item->>'location', ''),
        COALESCE(item->>'gameType', 'Ligaspiel'),
        COALESCE(item->>'gameDate', ''),
        COALESCE((item->>'homeTeamHalftimeScore')::INTEGER, 0),
        COALESCE((item->>'awayTeamHalftimeScore')::INTEGER, 0),
        COALESCE((item->>'homeTeamScore')::INTEGER, 0),
        COALESCE((item->>'awayTeamScore')::INTEGER, 0),
        COALESCE((item->>'elapsedSeconds')::INTEGER, 0)
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'games', '[]'::JSONB)) AS item;

    -- PLAYER_GAME
    INSERT INTO public.player_game (
        player_game_id, game_id, player_id, two_minute_suspensions,
        yellow_card, red_card, blue_card, is_on_court,
        plus_minus, seconds_played, active_suspension_until_seconds
    )
    SELECT
        (item->>'playerGameId')::INTEGER,
        (item->>'gameId')::INTEGER,
        (item->>'playerId')::INTEGER,
        COALESCE((item->>'twoMinuteSuspensions')::INTEGER, 0),
        COALESCE((item->>'yellowCard')::BOOLEAN, FALSE),
        COALESCE((item->>'redCard')::BOOLEAN, FALSE),
        COALESCE((item->>'blueCard')::BOOLEAN, FALSE),
        COALESCE((item->>'isOnCourt')::BOOLEAN, FALSE),
        COALESCE((item->>'plusMinus')::INTEGER, 0),
        COALESCE((item->>'secondsPlayed')::INTEGER, 0),
        NULLIF(item->>'activeSuspensionUntilSeconds', '')::INTEGER
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'playerGames', '[]'::JSONB)) AS item;

    -- FIELD_PLAYER_GAMESTATS
    INSERT INTO public.field_player_gamestats (
        field_player_gamestats_id, player_game_id,
        goals_scored, goales_attempted,
        penalties_scored, penalties_attempted, penalties_drawn,
        assists, steals, blocks, technical_mistakes
    )
    SELECT
        (item->>'fieldPlayerGamestatsId')::INTEGER,
        (item->>'playerGameId')::INTEGER,
        COALESCE((item->>'goalsScored')::INTEGER, 0),
        COALESCE((item->>'goalesAttempted')::INTEGER, 0),
        COALESCE((item->>'penaltiesScored')::INTEGER, 0),
        COALESCE((item->>'penaltiesAttempted')::INTEGER, 0),
        COALESCE((item->>'penaltiesDrawn')::INTEGER, 0),
        COALESCE((item->>'assists')::INTEGER, 0),
        COALESCE((item->>'steals')::INTEGER, 0),
        COALESCE((item->>'blocks')::INTEGER, 0),
        COALESCE((item->>'technicalMistakes')::INTEGER, 0)
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'fieldPlayerStats', '[]'::JSONB)) AS item;

    -- GOAL_KEEPER_GAMESTATS
    INSERT INTO public.goal_keeper_gamestats (
        goal_keeper_gamestats_id, player_game_id,
        saves, goales_conceded,
        penalties_saved, penalties_conceded,
        sucessful_fast_break_passes, attempted_fast_break_passes
    )
    SELECT
        (item->>'goalKeeperGamestatsId')::INTEGER,
        (item->>'playerGameId')::INTEGER,
        COALESCE((item->>'saves')::INTEGER, 0),
        COALESCE((item->>'goalesConceded')::INTEGER, 0),
        COALESCE((item->>'penaltiesSaved')::INTEGER, 0),
        COALESCE((item->>'penaltiesConceded')::INTEGER, 0),
        COALESCE((item->>'sucessfulFastBreakPasses')::INTEGER, 0),
        COALESCE((item->>'attemptedFastBreakPasses')::INTEGER, 0)
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'goalKeeperStats', '[]'::JSONB)) AS item;

    -- TIMEOUT
    INSERT INTO public.timeout (timeout_id, timeout_reason)
    SELECT
        (item->>'timeoutId')::INTEGER,
        COALESCE(item->>'timeoutReason', '')
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'timeouts', '[]'::JSONB)) AS item;

    -- COACH_GAMESTATS
    INSERT INTO public.coach_gamestats (coach_gamestats_id, player_game_id, timeout_id)
    SELECT
        (item->>'coachGamestatsId')::INTEGER,
        (item->>'playerGameId')::INTEGER,
        (item->>'timeoutId')::INTEGER
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'coachStats', '[]'::JSONB)) AS item;

    -- GAME_LOG
    INSERT INTO public.game_log (
        log_id, game_id, game_second, event_type,
        primary_player_id, secondary_player_id,
        home_score_at_event, away_score_at_event, description
    )
    SELECT
        (item->>'logId')::INTEGER,
        (item->>'gameId')::INTEGER,
        COALESCE((item->>'gameSecond')::INTEGER, 0),
        COALESCE(item->>'eventType', 'SCORE_UPDATE'),
        NULLIF(item->>'primaryPlayerId', '')::INTEGER,
        NULLIF(item->>'secondaryPlayerId', '')::INTEGER,
        COALESCE((item->>'homeScoreAtEvent')::INTEGER, 0),
        COALESCE((item->>'awayScoreAtEvent')::INTEGER, 0),
        COALESCE(item->>'description', '')
    FROM jsonb_array_elements(COALESCE(incoming_snapshot->'gameLogs', '[]'::JSONB)) AS item;

    RETURN incoming_snapshot;
END;
$$;

