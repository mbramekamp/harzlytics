-- 1. RELATIONALE TABELLEN (entsprechend HandballDatabase.sq & ER-Modell)

CREATE TABLE IF NOT EXISTS public.position (
    position_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.player (
    player_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id INTEGER REFERENCES public.position(position_id) ON DELETE SET NULL,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    email TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL DEFAULT 'FIELD_PLAYER',
    jersey_number_home_kit INTEGER,
    jersey_number_away_kit INTEGER
);

CREATE TABLE IF NOT EXISTS public.season (
    season_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division TEXT NOT NULL,
    start_of_season TEXT NOT NULL,
    end_of_season TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.opponent_teams (
    opponent_team_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opponent_name TEXT NOT NULL,
    opponent_location TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.season_opponent (
    season_id INTEGER NOT NULL REFERENCES public.season(season_id) ON DELETE CASCADE,
    opponent_team_id INTEGER NOT NULL REFERENCES public.opponent_teams(opponent_team_id) ON DELETE CASCADE,
    PRIMARY KEY (season_id, opponent_team_id)
);

CREATE TABLE IF NOT EXISTS public.game (
    game_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id INTEGER NOT NULL REFERENCES public.season(season_id) ON DELETE CASCADE,
    opponent_id INTEGER NOT NULL REFERENCES public.opponent_teams(opponent_team_id) ON DELETE CASCADE,
    second_opponent_id INTEGER REFERENCES public.opponent_teams(opponent_team_id) ON DELETE SET NULL,
    is_home_game BOOLEAN NOT NULL DEFAULT TRUE,
    location TEXT NOT NULL,
    game_type TEXT NOT NULL DEFAULT 'Ligaspiel',
    game_date TEXT NOT NULL,
    home_team_halftime_score INTEGER NOT NULL DEFAULT 0,
    away_team_halftime_score INTEGER NOT NULL DEFAULT 0,
    home_team_score INTEGER NOT NULL DEFAULT 0,
    away_team_score INTEGER NOT NULL DEFAULT 0,
    elapsed_seconds INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.player_game (
    player_game_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id INTEGER NOT NULL REFERENCES public.game(game_id) ON DELETE CASCADE,
    player_id INTEGER NOT NULL REFERENCES public.player(player_id) ON DELETE CASCADE,
    two_minute_suspensions INTEGER NOT NULL DEFAULT 0,
    yellow_card BOOLEAN NOT NULL DEFAULT FALSE,
    red_card BOOLEAN NOT NULL DEFAULT FALSE,
    blue_card BOOLEAN NOT NULL DEFAULT FALSE,
    is_on_court BOOLEAN NOT NULL DEFAULT FALSE,
    plus_minus INTEGER NOT NULL DEFAULT 0,
    seconds_played INTEGER NOT NULL DEFAULT 0,
    active_suspension_until_seconds INTEGER
);

CREATE TABLE IF NOT EXISTS public.field_player_gamestats (
    field_player_gamestats_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_game_id INTEGER NOT NULL REFERENCES public.player_game(player_game_id) ON DELETE CASCADE,
    goals_scored INTEGER NOT NULL DEFAULT 0,
    goales_attempted INTEGER NOT NULL DEFAULT 0,
    penalties_scored INTEGER NOT NULL DEFAULT 0,
    penalties_attempted INTEGER NOT NULL DEFAULT 0,
    penalties_drawn INTEGER NOT NULL DEFAULT 0,
    assists INTEGER NOT NULL DEFAULT 0,
    steals INTEGER NOT NULL DEFAULT 0,
    blocks INTEGER NOT NULL DEFAULT 0,
    technical_mistakes INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.goal_keeper_gamestats (
    goal_keeper_gamestats_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_game_id INTEGER NOT NULL REFERENCES public.player_game(player_game_id) ON DELETE CASCADE,
    saves INTEGER NOT NULL DEFAULT 0,
    goales_conceded INTEGER NOT NULL DEFAULT 0,
    penalties_saved INTEGER NOT NULL DEFAULT 0,
    penalties_conceded INTEGER NOT NULL DEFAULT 0,
    sucessful_fast_break_passes INTEGER NOT NULL DEFAULT 0,
    attempted_fast_break_passes INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.timeout (
    timeout_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timeout_reason TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.coach_gamestats (
    coach_gamestats_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_game_id INTEGER NOT NULL REFERENCES public.player_game(player_game_id) ON DELETE CASCADE,
    timeout_id INTEGER NOT NULL REFERENCES public.timeout(timeout_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.game_log (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id INTEGER NOT NULL REFERENCES public.game(game_id) ON DELETE CASCADE,
    game_second INTEGER NOT NULL DEFAULT 0,
    event_type TEXT NOT NULL,
    primary_player_id INTEGER REFERENCES public.player(player_id) ON DELETE SET NULL,
    secondary_player_id INTEGER REFERENCES public.player(player_id) ON DELETE SET NULL,
    home_score_at_event INTEGER NOT NULL DEFAULT 0,
    away_score_at_event INTEGER NOT NULL DEFAULT 0,
    description TEXT NOT NULL
);

-- 2. OFFLINE-FIRST SNAPSHOT-TABELLE
-- Speichert den vollständigen App-Snapshot als JSONB und synchronisiert ihn
-- automatisch mit allen 12 relationalen Tabellen oben.

CREATE TABLE IF NOT EXISTS public.app_snapshots (
    snapshot_key TEXT PRIMARY KEY DEFAULT 'default',
    own_club_name TEXT NOT NULL DEFAULT 'HC Handball Löwen',
    last_updated_epoch_millis BIGINT NOT NULL DEFAULT 0,
    payload JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

