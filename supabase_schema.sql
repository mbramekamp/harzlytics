-- =============================================================================
-- 3a. BENUTZERVERWALTUNG & ROLLEN (RBAC) – Auth Phase 1, siehe USER_FEATURE.md
-- =============================================================================
-- Sicherheitsregeln (abweichend vom ursprünglichen Entwurf in USER_FEATURE.md):
--   * Die Rolle wird NIE aus den Signup-Metadaten übernommen (sonst könnte sich jeder
--     als ADMIN registrieren). Rollen kommen nur aus einem gültigen Einladungscode
--     oder werden von einem ADMIN vergeben.
--   * Neue Konten ohne Einladung / Kader-Verknüpfung sind 'PENDING' und sehen keine Daten.
--   * Kader-Verknüpfung per E-Mail erst, wenn die E-Mail-Adresse bestätigt ist.
--   * user_profiles.player_id / club_invitations.player_id haben bewusst KEINEN
--     Foreign Key auf public.player: sync_handball_snapshot löscht und befüllt die
--     Tabelle player bei jedem Sync neu (gleiche IDs) – ein FK würde alle
--     Verknüpfungen auf NULL setzen bzw. Einladungen löschen.
--   * Nicht-Admins dürfen an ihrem Profil nur full_name und claim_player_id ändern.
--
-- ERSTEN ADMIN ANLEGEN (einmalig, nach der eigenen Registrierung, im SQL Editor):
--   UPDATE public.user_profiles SET role = 'ADMIN', status = 'ACTIVE'
--   WHERE email = '<deine-email>';

DO $$ BEGIN
    CREATE TYPE public.app_role AS ENUM ('SPIELER', 'TRAINER', 'ADMIN');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS public.user_profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    full_name TEXT NOT NULL DEFAULT '',
    role public.app_role NOT NULL DEFAULT 'SPIELER',
    player_id INTEGER,              -- verknüpfter Kader-Eintrag (public.player.player_id), ohne FK (s. o.)
    claim_player_id INTEGER,        -- vom Benutzer angefragte Verknüpfung, Freigabe durch ADMIN
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_user_profiles_player_id ON public.user_profiles(player_id);
CREATE INDEX IF NOT EXISTS idx_user_profiles_email ON public.user_profiles(LOWER(email));

CREATE TABLE IF NOT EXISTS public.club_invitations (
    invitation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invite_code TEXT NOT NULL UNIQUE CHECK (LENGTH(invite_code) >= 12),
    intended_role public.app_role NOT NULL DEFAULT 'SPIELER',
    player_id INTEGER,              -- optional: Einladung direkt für einen Kader-Eintrag, ohne FK (s. o.)
    max_uses INTEGER NOT NULL DEFAULT 1 CHECK (max_uses >= 1),
    uses_count INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMPTZ,
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Hilfsfunktionen für RLS & RPC. Liefern nur für freigeschaltete Profile (ACTIVE) Werte.
CREATE OR REPLACE FUNCTION public.current_user_role()
RETURNS public.app_role
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT role FROM public.user_profiles WHERE id = auth.uid() AND status = 'ACTIVE';
$$;

CREATE OR REPLACE FUNCTION public.current_player_id()
RETURNS INTEGER
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT player_id FROM public.user_profiles WHERE id = auth.uid() AND status = 'ACTIVE';
$$;

CREATE OR REPLACE FUNCTION public.is_active_member()
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT public.current_user_role() IS NOT NULL;
$$;

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT COALESCE(public.current_user_role() = 'ADMIN', FALSE);
$$;

CREATE OR REPLACE FUNCTION public.is_coach_or_admin()
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT COALESCE(public.current_user_role() IN ('TRAINER', 'ADMIN'), FALSE);
$$;

-- Profil bei Registrierung anlegen bzw. bei E-Mail-Bestätigung mit dem Kader verknüpfen.
CREATE OR REPLACE FUNCTION public.handle_auth_user_change()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
    v_invite public.club_invitations%ROWTYPE;
    v_code TEXT;
    v_role public.app_role := 'SPIELER';
    v_status TEXT := 'PENDING';
    v_player_id INTEGER;
    v_match_count INTEGER;
BEGIN
    IF TG_OP = 'INSERT' THEN
        -- Optionaler Einladungscode aus den Signup-Metadaten (nur der CODE wird vertraut,
        -- Rolle & Kader-Eintrag stammen aus der Einladung selbst).
        v_code := NULLIF(TRIM(NEW.raw_user_meta_data->>'invite_code'), '');
        IF v_code IS NOT NULL THEN
            SELECT * INTO v_invite
            FROM public.club_invitations
            WHERE invite_code = v_code
              AND uses_count < max_uses
              AND (expires_at IS NULL OR expires_at > NOW())
            FOR UPDATE;
            IF FOUND THEN
                UPDATE public.club_invitations
                SET uses_count = uses_count + 1
                WHERE invitation_id = v_invite.invitation_id;
                v_role := v_invite.intended_role;
                v_player_id := v_invite.player_id;
                v_status := 'ACTIVE';
            END IF;
        END IF;

        INSERT INTO public.user_profiles (id, email, full_name, role, player_id, status)
        VALUES (
            NEW.id,
            COALESCE(NEW.email, ''),
            LEFT(COALESCE(NEW.raw_user_meta_data->>'full_name', ''), 200),
            v_role,
            v_player_id,
            v_status
        )
        ON CONFLICT (id) DO NOTHING;
    END IF;

    -- Kader-Verknüpfung per E-Mail: nur mit bestätigter Adresse und eindeutigem Treffer.
    IF NEW.email_confirmed_at IS NOT NULL AND COALESCE(NEW.email, '') <> '' THEN
        SELECT COUNT(*), MIN(p.player_id) INTO v_match_count, v_player_id
        FROM public.player p
        WHERE p.email <> '' AND LOWER(p.email) = LOWER(NEW.email) AND p.role <> 'COACH';

        IF v_match_count = 1 THEN
            UPDATE public.user_profiles
            SET player_id = v_player_id,
                status = CASE WHEN status = 'PENDING' THEN 'ACTIVE' ELSE status END,
                updated_at = NOW()
            WHERE id = NEW.id AND player_id IS NULL AND status <> 'SUSPENDED';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_auth_user_change();

DROP TRIGGER IF EXISTS on_auth_user_email_confirmed ON auth.users;
CREATE TRIGGER on_auth_user_email_confirmed
    AFTER UPDATE OF email_confirmed_at ON auth.users
    FOR EACH ROW
    WHEN (OLD.email_confirmed_at IS NULL AND NEW.email_confirmed_at IS NOT NULL)
    EXECUTE FUNCTION public.handle_auth_user_change();

-- Schutz vor Rechteausweitung: Nicht-Admins dürfen nur full_name & claim_player_id ändern.
-- (auth.uid() IS NULL = SQL Editor / Service-Kontext / Auth-Trigger -> erlaubt)
CREATE OR REPLACE FUNCTION public.guard_user_profile_update()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
    IF auth.uid() IS NOT NULL AND NOT public.is_admin() THEN
        IF NEW.id IS DISTINCT FROM OLD.id
           OR NEW.email IS DISTINCT FROM OLD.email
           OR NEW.role IS DISTINCT FROM OLD.role
           OR NEW.status IS DISTINCT FROM OLD.status
           OR NEW.player_id IS DISTINCT FROM OLD.player_id
           OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
            RAISE EXCEPTION 'user_profiles: only an admin may change role, status or player link'
                USING ERRCODE = '42501';
        END IF;
    END IF;
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS guard_user_profile_update ON public.user_profiles;
CREATE TRIGGER guard_user_profile_update
    BEFORE UPDATE ON public.user_profiles
    FOR EACH ROW EXECUTE FUNCTION public.guard_user_profile_update();

